"""Render full-run results into README tables and context/recall SVG figures."""

from __future__ import annotations

import json
from pathlib import Path
from xml.sax.saxutils import escape

import numpy as np

from relpath_bench import registry
from relpath_bench.metrics import KS, QueryRecord
from relpath_bench.types import Limits

START = "<!-- RESULTS:START -->"
END = "<!-- RESULTS:END -->"
COLORS = ["#1f77b4", "#d62728", "#2ca02c", "#9467bd", "#ff7f0e", "#8c564b", "#17becf"]
HEADER = "| algorithm | hops | hit@1 | hit@10 | recall@10 | context@10 | p50 ms | capped |"


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def _table(rows: list[dict], order: list[str]) -> str:
    rows = sorted(rows, key=lambda r: (order.index(r["algorithm"]), str(r["hops"])))
    lines = [HEADER, "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for r in rows:
        lines.append(
            f"| {r['algorithm']} | {r['hops']} | {_pct(r['hit@1'])} | {_pct(r['hit@10'])} "
            f"| {_pct(r['recall@10'])} | {r['context@10']:.1f} | {r['p50_ms']:.1f} | {r['capped']} |"
        )
    return "\n".join(lines)


def _load_notes(stats: dict) -> list[str]:
    """Generated lines on data dropped while loading; empty when nothing was dropped."""
    lines = []
    dropped = stats.get("answers_dropped", 0)
    if dropped:
        lines.append(f"- answer names dropped (not nodes of the subgraph): {dropped:,}")
    no_answer = stats.get("examples_no_answer", 0)
    if no_answer:
        lines.append(
            f"- questions with no answer left: {no_answer:,} of {stats.get('examples', 0):,} "
            "(counted as misses in `all`)"
        )
    if dropped or no_answer:
        lines.append("- recall is computed over answers present in the graph")
    return lines


def _load_records(run: Path, algorithm: str) -> list[QueryRecord]:
    recs = []
    for line in (run / f"{algorithm}.jsonl").read_text().splitlines():
        if line.strip():
            recs.append(QueryRecord.from_json(line))
    return recs


def context_recall_svg(records_by_alg: dict[str, list[QueryRecord]]) -> str:
    """x = mean context@k, y = mean recall@k; one point per k, one line per algorithm."""
    series = {}
    for alg, recs in records_by_alg.items():
        series[alg] = [
            (float(np.mean([r.context[k] for r in recs])), float(np.mean([r.recalls[k] for r in recs])))
            for k in KS
        ]
    w, h, left, right, top, bottom = 640, 420, 70, 150, 40, 60
    xmax = max([x for pts in series.values() for x, _ in pts] + [1.0])
    ymax = max([y for pts in series.values() for _, y in pts] + [0.01])
    ymax = min(1.0, ymax * 1.1)

    def sx(x: float) -> float:
        return left + (w - left - right) * x / xmax

    def sy(y: float) -> float:
        return h - bottom - (h - top - bottom) * y / ymax

    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" '
        f'font-family="sans-serif" font-size="12">',
        "<title>Recall@k versus mean context triples per algorithm</title>",
        f'<rect width="{w}" height="{h}" fill="#ffffff"/>',
        f'<line x1="{left}" y1="{h - bottom}" x2="{w - right}" y2="{h - bottom}" stroke="#333"/>',
        f'<line x1="{left}" y1="{top}" x2="{left}" y2="{h - bottom}" stroke="#333"/>',
    ]
    for i in range(5):
        xv, yv = xmax * i / 4, ymax * i / 4
        out.append(f'<text x="{sx(xv):.1f}" y="{h - bottom + 16}" text-anchor="middle">{xv:.1f}</text>')
        out.append(f'<text x="{left - 8}" y="{sy(yv) + 4:.1f}" text-anchor="end">{yv:.2f}</text>')
        out.append(f'<line x1="{left}" y1="{sy(yv):.1f}" x2="{w - right}" y2="{sy(yv):.1f}" stroke="#ddd"/>')
    out.append(
        f'<text x="{(left + w - right) / 2:.0f}" y="{h - 22}" text-anchor="middle">mean context triples</text>'
    )
    out.append(
        f'<text x="18" y="{(top + h - bottom) / 2:.0f}" text-anchor="middle" '
        f'transform="rotate(-90 18 {(top + h - bottom) / 2:.0f})">recall@k</text>'
    )
    for i, (alg, pts) in enumerate(series.items()):
        c = COLORS[i % len(COLORS)]
        poly = " ".join(f"{sx(x):.1f},{sy(y):.1f}" for x, y in pts)
        out.append(f'<polyline points="{poly}" fill="none" stroke="{c}" stroke-width="2"/>')
        for k, (x, y) in zip(KS, pts):
            out.append(
                f'<circle cx="{sx(x):.1f}" cy="{sy(y):.1f}" r="4" fill="{c}"><title>{escape(alg)} k={k}</title></circle>'
            )
        ly = top + 18 * i
        out.append(f'<rect x="{w - right + 16}" y="{ly}" width="12" height="12" fill="{c}"/>')
        out.append(f'<text x="{w - right + 34}" y="{ly + 11}">{escape(alg)}</text>')
    out.append(
        f'<text x="{w - 6}" y="{h - 6}" text-anchor="end" font-size="9" fill="#888">'
        "generated by relpath-bench report</text>"
    )
    out.append("</svg>")
    return "\n".join(out) + "\n"


def render(out: Path, readme: Path) -> None:
    """Replace the README results block using ``*-full`` runs under ``out`` only."""
    import relpath_bench.retrievers  # noqa: F401  (registers every retriever)

    out, readme = Path(out), Path(readme)
    order = registry.names()
    runs = sorted(p.parent for p in out.glob("*/*-full/summary.json")) if out.is_dir() else []
    if not runs:
        raise SystemExit(f"no full run found under {out}; run with --full first")
    figdir = readme.parent / "docs" / "figures"
    sections: list[str] = []
    seen: set[str] = set()
    for run in runs:
        summary = json.loads((run / "summary.json").read_text())
        dataset = summary["dataset"]
        if dataset in seen:
            continue
        seen.add(dataset)
        missing = [a for a in order if not (run / f"{a}.jsonl").exists()]
        if missing:
            raise SystemExit(f"{dataset} full run is missing algorithms: {', '.join(missing)}")
        rows = [r for r in summary["rows"] if r["algorithm"] in order]
        by_hops = any(r["hops"] != "all" for r in rows)
        parts = [f"### {dataset} ({run.name})"]
        all_rows = [r for r in rows if r["subset"] == "all"]
        notes = _load_notes(summary.get("load_stats") or {})
        if by_hops:
            first = [r for r in all_rows if r["algorithm"] == order[0] and "reachable_ratio" in r]
            if first:
                ratios = ", ".join(
                    f"{r['hops']}-hop {100 * r['reachable_ratio']:.2f}%"
                    for r in sorted(first, key=lambda r: str(r["hops"]))
                )
                parts.append(f"reachable_ratio by hops (answer within {Limits().max_hops} hops of a seed): {ratios}")
            parts.append(_table(all_rows, order))
        else:
            ratios = ", ".join(f"{r['algorithm']} {_pct(r['reachable_ratio'])}" for r in sorted(all_rows, key=lambda r: order.index(r["algorithm"])))
            parts.append(f"reachable_ratio (answer within {Limits().max_hops} hops of a seed): {ratios}")
            parts.append("Subset `all`\n\n" + _table(all_rows, order))
            reach = [r for r in rows if r["subset"] == "reachable"]
            if reach:
                parts.append("Subset `reachable`\n\n" + _table(reach, order))
        if notes:
            parts.append("\n".join(notes))
        svg = context_recall_svg({a: _load_records(run, a) for a in order})
        figdir.mkdir(parents=True, exist_ok=True)
        (figdir / f"{dataset}_context_recall.svg").write_text(svg)
        parts.append(f"![{dataset} recall versus context](docs/figures/{dataset}_context_recall.svg)")
        sections.append("\n\n".join(parts))
    text = readme.read_text()
    if START not in text or END not in text or text.index(START) > text.index(END):
        raise SystemExit(f"README is missing the {START} / {END} markers")
    head, rest = text.split(START, 1)
    tail = rest.split(END, 1)[1]
    readme.write_text(f"{head}{START}\n" + "\n\n".join(sections) + f"\n{END}{tail}")
