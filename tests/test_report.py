def _readme(tmp_path):
    readme = tmp_path / "README.md"
    readme.write_text("x\n<!-- RESULTS:START -->\nold\n<!-- RESULTS:END -->\ny\n")
    return readme


def test_render_replaces_block(tmp_path, full_summary_fixture):
    readme = _readme(tmp_path)
    render(full_summary_fixture, readme)
    text = readme.read_text()
    assert "old" not in text and "| bfs |" in text and text.startswith("x\n") and text.endswith("y\n")
    assert "| algorithm | hops | hit@1 | hit@10 | recall@10 | context@10 | p50 ms | capped |" in text
    assert "50.0%" in text
    assert "reachable_ratio" in text and "docs/figures/metaqa_context_recall.svg" in text
    assert (tmp_path / "docs/figures/webqsp_context_recall.svg").exists()
    names = [n for n in registry.names()]
    assert text.index(f"| {names[0]} |") < text.index(f"| {names[-1]} |")


def test_render_is_idempotent(tmp_path, full_summary_fixture):
    readme = _readme(tmp_path)
    render(full_summary_fixture, readme)
    first = readme.read_text()
    render(full_summary_fixture, readme)
    assert readme.read_text() == first


def test_render_refuses_sample_only(tmp_path, sample_summary_fixture):
    with pytest.raises(SystemExit, match="full"):
        render(sample_summary_fixture, _readme(tmp_path))


def test_render_refuses_missing_results_dir(tmp_path):
    with pytest.raises(SystemExit, match="full"):
        render(tmp_path / "nothing", _readme(tmp_path))


def test_render_refuses_missing_algorithm(tmp_path, full_summary_without_pcst):
    with pytest.raises(SystemExit, match="pcst"):
        render(full_summary_without_pcst, _readme(tmp_path))


def test_render_requires_markers(tmp_path, full_summary_fixture):
    readme = tmp_path / "README.md"
    readme.write_text("no markers\n")
    with pytest.raises(SystemExit, match="RESULTS"):
        render(full_summary_fixture, readme)


def test_svg_well_formed():
    svg = context_recall_svg({"bfs": [_rec("bfs", "a", 1, 1)], "ppr": [_rec("ppr", "a", 1, 0)]})
    root = ET.fromstring(svg)
    assert "<title>" in svg and "generated by relpath-bench report" in svg
    assert "mean context triples" in svg and "recall@k" in svg
    assert svg.count("<polyline") == 2
    assert svg.count("<circle") == 2 * len(KS)
    assert root.tag.endswith("svg")
